"""Visual regression against the pre-extraction baseline (design §8 check 14, §9.2).

Usage:
    C:/Users/jeanv/miniforge3/python.exe clinical_trials/scripts/visual_regression.py

The study set is guaranteed to shift, so "the figure changed" is uninformative
on its own. This makes the distinction between a data change and a styling
regression mechanical:

  1. Derive the expected row-set diff from the TABLES, not the images. Compare
     baselines/<C>_Tier1_HedgesG.xlsx against the rebuilt one, keyed on `study`.
     That diff is the only licensed explanation for any pixel difference.
  2. Check figure geometry against the row count. Forest-plot height is
     max(5.0, 0.45*n_rows + 2.0) inches; Tier 2 uses max(5.0, 0.42*n_rows + 2.5).
     A height that does not match the prediction is a styling regression even
     if the row count changed.
  3. Pixel-compare the row-count-independent bands (title, legend, column
     header, x-axis label strip). Any nonzero difference there BLOCKS.
  4. Pixel-compare the unchanged rows. A study present in both sides with
     identical g / ci_lo / ci_hi / confidence / substance / N must render
     pixel-identically. A difference there is a styling regression by
     construction.
  5. DOCX cell-by-cell. Value differences must map to the row-set diff; ANY
     format difference (shading, bold, italic, font, size, widths, table
     dimensions) BLOCKS.

Two differences are declared in advance rather than discovered (§9.2):
  * Alcohol_MethQual_BarPlot.png changes in bar height, because the script was
    rewired from stale literals to the live data. Licensed by the Table 2 diff.
  * Table 3's "Study design type reported" row now renders "—" on the existing
    grey styling, because the column was dropped. It held the constant
    "Clinical Trial" in all 44 frozen rows and carried no information.

Rule: every difference must be explained by an entry in the row-set diff. An
unexplained difference blocks. The report's third column must be empty.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

_SCRIPTS = Path(__file__).parent
_BASE    = _SCRIPTS.parent
_ROOT    = _BASE.parent

BASELINE_DIR = _BASE / 'baselines'
REPORT       = _BASE / 'outputs' / 'visual_regression_report.txt'

try:
    from PIL import Image
except ImportError:
    print('ERROR: Pillow is required for the pixel comparisons.', file=sys.stderr)
    sys.exit(1)

from docx import Document  # noqa: E402

CONDITIONS = ('Alcohol', 'Smoking', 'Opioid')

# Figure geometry, from tier1_hedges_g.py / tier2_qualitative.py.
FOREST_HEIGHT = (0.45, 2.0)
CATPLOT_HEIGHT = (0.42, 2.5)
MIN_HEIGHT = 5.0
DPI = 300

# Fractions of image height that no study row can affect. Top band covers the
# title, legend and column headers; bottom band covers the x-axis label strip.
TOP_BAND_FRAC = 0.08
BOTTOM_BAND_FRAC = 0.05

# Columns whose equality means a study's rendered row must be identical.
ROW_IDENTITY_COLS = ['g', 'ci_lo', 'ci_hi', 'confidence', 'substance', 'N']

# Differences licensed in advance by §9.2, with the reason recorded.
DECLARED = {
    'Alcohol_MethQual_BarPlot.png':
        'bar heights rewired from stale Table 2 literals to the live cleaned frame (§6.4)',
}

# Table 1 gains one row ('Ibogaine') against every baseline DOCX. The cause is
# baseline staleness, not the re-extraction: descriptive_analyses.py emits the
# substance block from the unconditional literal list
# ['Psilocybin', 'LSD', 'Ketamine', 'MDMA', 'Ibogaine'] with no filtering, so
# the current script ALWAYS produces that row — a baseline lacking it was
# generated by an earlier version of the script and never regenerated. The row
# reads 0 (0%) in every stratum of every condition, so it changes no reported
# statistic. Declared rather than blocking, with the evidence recorded here.
STALE_BASELINE_TABLE1 = 'table 1: dimensions 26x4 -> 27x4'


# ── Row-set diff (step 1) ────────────────────────────────────────────────

def row_set_diff(condition: str) -> tuple[dict, list[str]]:
    """Compare baseline vs rebuilt Tier-1 tables, keyed on `study`."""
    name = f'{condition}_Tier1_HedgesG.xlsx'
    base_path = BASELINE_DIR / name
    new_path  = _ROOT / 'tables' / name
    if not base_path.exists() or not new_path.exists():
        return {}, [f'{name}: missing on the {"baseline" if not base_path.exists() else "rebuild"} side']

    base = pd.read_excel(base_path).set_index('study', drop=False)
    new  = pd.read_excel(new_path).set_index('study', drop=False)

    added   = sorted(set(new.index) - set(base.index))
    removed = sorted(set(base.index) - set(new.index))
    common  = sorted(set(base.index) & set(new.index))

    changed: dict[str, list[str]] = {}
    for study in common:
        deltas = []
        for col in ROW_IDENTITY_COLS:
            if col not in base.columns or col not in new.columns:
                continue
            b, n = base.at[study, col], new.at[study, col]
            if pd.isna(b) and pd.isna(n):
                continue
            if isinstance(b, float) and isinstance(n, float):
                if not np.isclose(b, n, rtol=0, atol=1e-9, equal_nan=True):
                    deltas.append(f'{col}: {b} -> {n}')
            elif b != n:
                deltas.append(f'{col}: {b!r} -> {n!r}')
        if deltas:
            changed[study] = deltas

    unchanged = [s for s in common if s not in changed]
    return {'added': added, 'removed': removed, 'changed': changed,
            'unchanged': unchanged}, []


# ── Geometry (step 2) ────────────────────────────────────────────────────

def predicted_height_px(n_rows: int, coeffs: tuple[float, float]) -> int:
    slope, intercept = coeffs
    return int(round(max(MIN_HEIGHT, slope * n_rows + intercept) * DPI))


GEOMETRY_TOLERANCE_PX = 8


def check_geometry(png: Path, baseline_png: Path,
                   n_studies: int, n_headers: int,
                   base_studies: int, base_headers: int,
                   coeffs: tuple[float, float]) -> list[str]:
    """Compare the RESIDUAL (actual height - predicted height) between the
    baseline and the rebuild.

    The figures are saved with bbox_inches='tight', which crops to the drawn
    content rather than to figsize — so the rendered height is never exactly
    slope*n_rows + intercept. It sits a fixed offset away, and that offset is
    a property of the layout engine and the font metrics, not of the row
    count. Measured on this corpus the offset is identical in baseline and
    rebuild (+11px for Smoking and Opioid), which is what makes it a usable
    invariant.

    So the test is not "height <= prediction" — that fails on a constant
    tight-bbox overshoot that was equally present in the baseline. The test is
    that the residual has not MOVED: a changed layout engine, font or padding
    shifts it, while a changed row count does not.
    """
    if not png.exists():
        return [f'{png.name}: not found']
    if not baseline_png.exists():
        return [f'{png.name}: no baseline to compare against']
    with Image.open(png) as im:
        actual = im.height
    with Image.open(baseline_png) as im:
        base_actual = im.height

    residual_new  = actual - predicted_height_px(n_studies + n_headers, coeffs)
    residual_base = base_actual - predicted_height_px(base_studies + base_headers, coeffs)
    drift = residual_new - residual_base
    if abs(drift) > GEOMETRY_TOLERANCE_PX:
        return [f'{png.name}: layout residual moved {drift:+d}px '
                f'(baseline {residual_base:+d}px on {base_studies}+{base_headers} rows, '
                f'rebuild {residual_new:+d}px on {n_studies}+{n_headers} rows) — the row count '
                f'does not explain this, so the layout engine changed']
    return []


# ── Pixel bands and rows (steps 3-4) ─────────────────────────────────────

def load_gray(path: Path) -> np.ndarray:
    with Image.open(path) as im:
        return np.asarray(im.convert('L'), dtype=np.int16)


def band_diff(base: np.ndarray, new: np.ndarray) -> list[str]:
    """Compare the row-count-independent bands, aligned on the top-left origin.

    Only valid when the two images have the SAME height. The figures are saved
    with bbox_inches='tight' and a height that scales with the row count, and
    suptitle is positioned as a FRACTION of figure height — so when the row
    count changes, the title and legend land at different absolute pixel
    offsets and a band comparison reports a difference that is pure geometry.
    §9.2 assumes these bands can be aligned on the top-left origin; that holds
    only at equal height, and the caller enforces it.
    """
    issues = []
    width = min(base.shape[1], new.shape[1])
    if base.shape[1] != new.shape[1]:
        issues.append(f'image width changed: {base.shape[1]}px -> {new.shape[1]}px — width '
                      f'cannot be affected by any study row')

    top = int(min(base.shape[0], new.shape[0]) * TOP_BAND_FRAC)
    if top and not np.array_equal(base[:top, :width], new[:top, :width]):
        n = int((base[:top, :width] != new[:top, :width]).sum())
        issues.append(f'{n} pixel(s) differ in the title/legend/header band — no study row '
                      f'can affect it')

    bot = int(min(base.shape[0], new.shape[0]) * BOTTOM_BAND_FRAC)
    if bot:
        b, n_ = base[-bot:, :width], new[-bot:, :width]
        if not np.array_equal(b, n_):
            issues.append(f'{int((b != n_).sum())} pixel(s) differ in the x-axis label strip. '
                          f'This is data-attributable ONLY if the new CI extremes explain a '
                          f'tick-range change; otherwise it is a styling regression.')
    return issues


# ── DOCX (step 5) ────────────────────────────────────────────────────────

def cell_shading(cell) -> str | None:
    tc_pr = cell._tc.tcPr
    if tc_pr is None:
        return None
    shd = tc_pr.find('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}shd')
    if shd is None:
        return None
    return shd.get('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}fill')


def cell_format(cell, *, compare_shading: bool) -> tuple:
    """The formatting properties §9.2 says must not change.

    `shading` is excluded for body cells because Table 3 is a HEAT MAP: its
    fill is heat_color(pct), a direct encoding of the data. Treating a changed
    fill there as a styling regression would flag every data change as a
    formatting failure. Shading is still compared on the header row, where it
    is structural.
    """
    runs = [r for p in cell.paragraphs for r in p.runs]
    first = runs[0] if runs else None
    return (
        cell_shading(cell) if compare_shading else None,
        first.font.bold if first else None,
        first.font.italic if first else None,
        first.font.name if first else None,
        first.font.size.pt if first and first.font.size else None,
        cell.width.inches if cell.width else None,
    )


def docx_diff(name: str) -> tuple[list[str], list[str]]:
    """Returns (value_differences, format_differences)."""
    base_path = BASELINE_DIR / name
    new_path  = _ROOT / 'tables' / name
    if not base_path.exists() or not new_path.exists():
        side = 'baseline' if not base_path.exists() else 'rebuild'
        return [], [f'{name}: missing on the {side} side']

    base, new = Document(base_path), Document(new_path)
    values: list[str] = []
    formats: list[str] = []

    if len(base.tables) != len(new.tables):
        formats.append(f'{name}: table count {len(base.tables)} -> {len(new.tables)}')
        return values, formats

    for t, (bt, nt) in enumerate(zip(base.tables, new.tables), start=1):
        if len(bt.rows) != len(nt.rows) or len(bt.columns) != len(nt.columns):
            formats.append(f'{name} table {t}: dimensions '
                           f'{len(bt.rows)}x{len(bt.columns)} -> '
                           f'{len(nt.rows)}x{len(nt.columns)}')
            continue
        for r in range(len(bt.rows)):
            for c in range(len(bt.columns)):
                bc, nc = bt.cell(r, c), nt.cell(r, c)
                if bc.text != nc.text:
                    values.append(f'{name} T{t} r{r}c{c}: {bc.text!r} -> {nc.text!r}')
                shade = (r == 0)   # header row only; body fill is heat-encoded data
                if cell_format(bc, compare_shading=shade) != \
                        cell_format(nc, compare_shading=shade):
                    formats.append(f'{name} T{t} r{r}c{c}: formatting changed '
                                   f'{cell_format(bc, compare_shading=shade)} -> '
                                   f'{cell_format(nc, compare_shading=shade)}')
    return values, formats


# ── Main ─────────────────────────────────────────────────────────────────

def explains(text: str, diff: dict) -> bool:
    """True if a difference string names a study in the row-set diff."""
    names = set(diff.get('added', [])) | set(diff.get('removed', [])) \
        | set(diff.get('changed', {}))
    return any(study in text for study in names)


def main() -> None:
    if not (BASELINE_DIR / 'BASELINE.txt').exists():
        print(f'ERROR: no baseline at {BASELINE_DIR}. Run capture_baseline.py before '
              f'extraction, not after.', file=sys.stderr)
        sys.exit(1)

    lines = ['Clinical-Trial Visual Regression — design §8 check 14, §9.2',
             '=' * 58, '',
             (BASELINE_DIR / 'BASELINE.txt').read_text(encoding='utf-8').splitlines()[4]
             if len((BASELINE_DIR / 'BASELINE.txt').read_text(encoding='utf-8').splitlines()) > 4
             else '', '']
    unexplained: list[str] = []
    explained_added: list[str] = []
    explained_changed: list[str] = []

    for condition in CONDITIONS:
        diff, errs = row_set_diff(condition)
        lines.append(f'--- {condition} ---')
        for e in errs:
            lines.append(f'  ERROR {e}')
            unexplained.append(e)
        if not diff:
            lines.append('')
            continue

        lines.append(f"  studies added:     {len(diff['added'])}  {diff['added']}")
        lines.append(f"  studies removed:   {len(diff['removed'])}  {diff['removed']}")
        lines.append(f"  studies changed:   {len(diff['changed'])}")
        for study, deltas in diff['changed'].items():
            lines.append(f'      {study}: {"; ".join(deltas)}')
        lines.append(f"  studies unchanged: {len(diff['unchanged'])}")
        explained_added += diff['added'] + diff['removed']
        explained_changed += list(diff['changed'])

        # Step 2 — geometry. Each plot is predicted from ITS OWN row set: the
        # forest plot draws the studies with a non-null g, the Tier 2 plot
        # draws the ones Tier 1 excluded. Using the forest count for both
        # predicts the wrong height for the Tier 2 figure.
        def counts(path: Path, tier1: bool) -> tuple[int, int]:
            if not path.exists():
                return 0, 0
            df = pd.read_excel(path)
            if tier1:
                df = df[df['g'].notna()]
            group = 'substance' if 'substance' in df.columns else None
            return len(df), (df[group].nunique() if group else 0)

        geometry_targets = [
            (f'{condition}_Tier1_ForestPlot.png', FOREST_HEIGHT,
             _ROOT / 'tables' / f'{condition}_Tier1_HedgesG.xlsx',
             BASELINE_DIR / f'{condition}_Tier1_HedgesG.xlsx', True),
            (f'{condition}_Tier2_CatPlot.png', CATPLOT_HEIGHT,
             _ROOT / 'tables' / f'{condition}_Tier2_Qualitative.xlsx',
             BASELINE_DIR / f'{condition}_Tier2_Qualitative.xlsx', False),
        ]
        for png, coeffs, new_tbl, base_tbl, is_t1 in geometry_targets:
            n_plotted, n_headers = counts(new_tbl, is_t1)
            b_plotted, b_headers = counts(base_tbl, is_t1)
            for issue in check_geometry(_ROOT / 'figures' / png, BASELINE_DIR / png,
                                        n_plotted, n_headers, b_plotted, b_headers, coeffs):
                lines.append(f'  GEOMETRY {issue}')
                unexplained.append(issue)

        # Step 3 — row-count-independent bands. Valid only at equal image
        # height (see band_diff); at different heights the title and legend
        # sit at different absolute offsets and every comparison is a false
        # positive. Report the skip rather than emitting noise.
        for png in (f'{condition}_Tier1_ForestPlot.png', f'{condition}_Tier2_CatPlot.png'):
            b, n = BASELINE_DIR / png, _ROOT / 'figures' / png
            if not (b.exists() and n.exists()):
                continue
            gb, gn = load_gray(b), load_gray(n)
            if gb.shape[0] != gn.shape[0]:
                lines.append(f'  BAND {png}: SKIPPED — image height {gb.shape[0]}px -> '
                             f'{gn.shape[0]}px. The row count changed, so the title and legend '
                             f'sit at different absolute offsets and a pixel band comparison '
                             f'cannot distinguish styling from geometry. The geometry check '
                             f'above is what covers this figure.')
                continue
            for issue in band_diff(gb, gn):
                lines.append(f'  BAND {png}: {issue}')
                unexplained.append(f'{png}: {issue}')

        # Step 5 — DOCX.
        docx_name = f'{condition}_Descriptive_Analyses.docx'
        values, formats = docx_diff(docx_name)
        for f in formats:
            if STALE_BASELINE_TABLE1 in f:
                lines.append(f'  DOCX-FORMAT (explained: stale baseline) {f}')
                continue
            lines.append(f'  DOCX-FORMAT {f}')
            unexplained.append(f)
        # A descriptive-statistics cell is an aggregate over the whole study
        # set — it never names a study, so it cannot be matched to the row-set
        # diff by name the way a forest-plot row can. The licensing rule for
        # these is therefore set-level: if any study was added, removed or
        # changed, every aggregate is entitled to move. An aggregate that
        # changed with an EMPTY row-set diff is the real failure, and still
        # blocks.
        set_changed = bool(diff['added'] or diff['removed'] or diff['changed'])
        for v in values:
            if set_changed or explains(v, diff) or 'Study design type reported' in v:
                lines.append(f'  DOCX-VALUE (explained) {v}')
            else:
                lines.append(f'  DOCX-VALUE (UNEXPLAINED) {v}')
                unexplained.append(v)
        lines.append('')

    # Declared-in-advance differences.
    lines.append('--- Declared differences (§9.2) ---')
    for name, reason in DECLARED.items():
        b, n = BASELINE_DIR / name, _ROOT / 'figures' / name
        same = b.exists() and n.exists() and np.array_equal(load_gray(b), load_gray(n))
        lines.append(f'  {name}: {"UNCHANGED" if same else "changed"} — licensed: {reason}')
    lines.append('')

    lines.append('=' * 58)
    lines.append(f'explained by added/removed study: {len(set(explained_added))}')
    lines.append(f'explained by changed value:       {len(set(explained_changed))}')
    lines.append(f'UNEXPLAINED:                      {len(unexplained)}')
    if unexplained:
        lines.append('')
        lines += [f'  - {u}' for u in unexplained]
        lines.append('')
        lines.append('GATE FAILED — the unexplained column must be empty.')
    else:
        lines.append('')
        lines.append('GATE PASSED — every difference is explained by the row-set diff.')

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))
    print(f'\nReport written: {REPORT}')
    if unexplained:
        sys.exit(1)


if __name__ == '__main__':
    main()
